def merge(target, source):
    added = 0
    for key, value in source.items():
        if isinstance(value, dict):
            existing = target.setdefault(key, {})
            if not isinstance(existing, dict):
                raise SystemExit(f"collision at {key!r}: existing value is not an object")
            added += merge(existing, value)
        elif key not in target:
            target[key] = value
            added += 1
    return added


def write(path, data):
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")


def main():
    for locale in sorted(EXTENDED):
        core_path = os.path.join(ROOT, locale, "core.json")
        with open(core_path, encoding="utf-8") as fh:
            core = json.load(fh)
        n_core = merge(core.setdefault("common", {}).setdefault("screens", {}), CORE[locale])
        write(core_path, core)

        ext_path = os.path.join(ROOT, locale, "extended.json")
        with open(ext_path, encoding="utf-8") as fh:
            ext = json.load(fh)
        n_ext = merge(ext.setdefault("premium", {}).setdefault("privateOffice", {}), EXTENDED[locale])
        write(ext_path, ext)

        print(f"{locale}: core +{n_core}, extended +{n_ext}")


if __name__ == "__main__":
    main()
