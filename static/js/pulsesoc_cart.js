/*
 * The web Marketplace cart, and the web's half of Marketplace checkout.
 *
 * Consumes services/marketplace_cart_routes.py unchanged. No endpoint here is
 * new and none is web-specific: the native app calls the same seven. The cart
 * itself is a server-side row set (marketplace_cart_items keyed on the buyer),
 * so this file is a second view of the app's cart rather than a second cart.
 *
 * Five rules this file exists to keep, all of them learned the hard way
 * elsewhere in this codebase:
 *
 * 1. Error and empty never co-render. `show()` is the only thing that toggles
 *    the four panels, and it takes exactly one of them. A failed fetch is not
 *    an empty cart, and a cart page that shows "nothing here yet" after a 500
 *    tells the buyer their items are gone.
 *
 * 2. The state words are the server's. `_line_state()` returns available,
 *    price_changed, low_stock, sold, restricted or removed, and each is printed
 *    as itself. Flattening them to in-stock/out-of-stock would drop
 *    price_changed, which is the one a buyer has to see before paying.
 *
 * 3. Every mutation re-reads. PATCH and DELETE return only the line they
 *    touched, and a quantity change can move a line from available to
 *    low_stock, so the list is refetched rather than patched in place. Local
 *    edits would drift from the states above the moment stock moved.
 *
 * 4. The page is grouped the way checkout transacts. `POST /checkout` takes one
 *    `seller_user_id` and settles that seller's lines as one charge, refusing
 *    the whole group for one sold line, one unconfirmed price or two
 *    currencies. A single cross-seller subtotal of the individually-purchasable
 *    lines would promise a payment the server does not offer. The groups, their
 *    verdicts and their reasons all arrive in the cart payload's `groups` --
 *    computed by services/marketplace_cart_web.py from the same rules the
 *    checkout lane enforces. Nothing in this file decides who may pay.
 *
 * 5. This file names no form field. The checkout lane demands buyer details
 *    whose field list differs per fulfilment kind and, for tickets, per
 *    listing; the server sends that list with the group, generated by
 *    `marketplace_fulfillment.buyer_form`, and the loop below renders whatever
 *    it is handed, keyed by field *type*. `mobile-native`'s
 *    marketplaceFulfillment.ts is a declared port of that table, pinned to it
 *    by a test on each side. A third copy in vanilla JS would be a third thing
 *    to keep pinned, and the one most likely to rot.
 *
 * No card details are collected here, on any path. The checkout lane returns a
 * Stripe-hosted Checkout Session URL and this file navigates to it, so the card
 * number is typed on Stripe's page and this origin never sees it. There is no
 * Stripe.js on this page and no element on it that could accept a PAN.
 */
(function () {
  "use strict";

  var root = document.querySelector("[data-cart-root]");
  if (!root) return;

  var els = {
    needsjs: root.querySelector("[data-cart-needsjs]"),
    fail: root.querySelector("[data-cart-fail]"),
    lines: root.querySelector("[data-cart-lines]"),
    empty: root.querySelector("[data-cart-empty]"),
    summary: root.querySelector("[data-cart-summary]")
  };

  // What the buyer has done to this page that the server does not know about:
  // which group's checkout form is open, which lane was chosen, and what has
  // been typed into it. Held here because every mutation re-reads (rule 3), and
  // a re-render that dropped a half-typed address would make the cart unusable
  // the moment an unrelated quantity changed.
  var ui = { open: 0, lane: {}, typed: {}, error: {}, busy: false };

  // The one place panel visibility is decided, so two of them cannot be shown
  // at once by a later edit that only remembered to turn one on.
  function show(which) {
    els.needsjs.hidden = true;
    els.fail.hidden = which !== "fail";
    els.lines.hidden = which !== "lines";
    els.empty.hidden = which !== "empty";
    els.summary.hidden = which !== "lines";
  }

  function esc(value) {
    return String(value === null || value === undefined ? "" : value)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
  }

  // Minor units to a readable amount. Intl decides the fraction digits from the
  // currency rather than assuming two, because the API returns whatever the
  // listing is priced in and a hardcoded /100 is wrong for JPY.
  function money(minor, currency) {
    var code = (currency || "USD").toUpperCase();
    try {
      var fmt = new Intl.NumberFormat(undefined, { style: "currency", currency: code });
      var digits = fmt.resolvedOptions().maximumFractionDigits;
      return fmt.format((minor || 0) / Math.pow(10, digits));
    } catch (err) {
      return ((minor || 0) / 100).toFixed(2) + " " + code;
    }
  }

  // Where a product lives, from the app-link registry rather than from a string
  // built here. services/app_links.py owns what a PulseSoc destination's link
  // looks like; the template injects its template form and this substitutes the
  // id into it. A path concatenated here would keep producing the right one
  // right through a change to that registry, and would go on *working* while
  // every other surface moved -- which is why the test that enforces this
  // forbids the product path from appearing in a script at all, including in a
  // comment like this one.
  var PRODUCT_HREF = root.getAttribute("data-cart-product-href") || "";
  function productHref(listingId) {
    return PRODUCT_HREF.replace("__RESOURCE_ID__", encodeURIComponent(String(listingId)));
  }

  // Server state -> what the buyer reads, and whether the line can be paid for.
  // `buys` is not derived from a "not one of the bad ones" test: a state this
  // file has never heard of must not be assumed purchasable.
  var STATES = {
    available:     { word: "Ready",         tone: "ok",   buys: true },
    price_changed: { word: "Price changed", tone: "attn", buys: false },
    low_stock:     { word: "Low stock",     tone: "attn", buys: true },
    sold:          { word: "Sold out",      tone: "gone", buys: false },
    restricted:    { word: "Unavailable",   tone: "gone", buys: false },
    removed:       { word: "Removed",       tone: "gone", buys: false }
  };

  function stateOf(name) {
    return STATES[name] || { word: String(name || "Unavailable"), tone: "gone", buys: false };
  }

  // ----------------------------------------------------------------------
  // The four steps this checkout actually has
  // ----------------------------------------------------------------------
  // Every one of these is a real stage with a real authority behind it, not a
  // wizard invented to look like one: this page collects the details, Stripe's
  // hosted page takes the payment, and the confirmation is written by the
  // webhook. The page does not advance the indicator itself past the step it is
  // on -- "Payment" lights up when the buyer is on Stripe's page, and nothing
  // here may draw "Confirmation" as reached, because this origin never learns
  // that a card was charged.
  //
  // It exists because the previous form ended in a button that said "Pay", which
  // promised a charge that this origin cannot and does not perform. Telling the
  // buyer there are two more stages after this one is the honest version of that
  // button.
  var STEPS = ["Cart", "Details", "Payment", "Confirmation"];

  // Step two is named after what the group's own form asks for. "Delivery" over
  // a pickup form is a false statement about where the order is going, and this
  // cart serves nine fulfilment kinds, not one. `details_kind` is the server's
  // word -- services/marketplace_fulfillment decides it -- and a kind this table
  // has never heard of falls through to the neutral noun rather than being
  // guessed at, the same rule `stateOf` above keeps for line states.
  var DETAIL_COPY = {
    shipping: {
      step: "Delivery", cta: "Proceed to delivery", title: "Delivery details",
      lede: "Where should this order go? The seller ships to the address you give here."
    },
    pickup: {
      step: "Pickup", cta: "Proceed to pickup details", title: "Pickup details",
      lede: "Who is collecting this, and how can the seller reach them?"
    },
    // `details_kind_for` answers "" for a group it asks nothing of -- an
    // all-digital basket -- and "" is a key like any other here rather than a
    // falsy value that falls through to the generic "the seller needs these",
    // which would be asking for details on a form that has none.
    "": {
      step: "Details", cta: "Continue to checkout", title: "Nothing to deliver",
      lede: "This order needs no delivery details. Continue when you are ready."
    },
    service_remote: {
      step: "Booking", cta: "Proceed to booking details", title: "Booking details",
      lede: "When would you like this, and how should the seller reach you?"
    },
    service_in_person: {
      step: "Booking", cta: "Proceed to booking details", title: "Booking details",
      lede: "When and where should the seller come to you?"
    },
    booking_remote: {
      step: "Booking", cta: "Proceed to booking details", title: "Booking details",
      lede: "When would you like this, and how should the seller reach you?"
    },
    booking_in_person: {
      step: "Booking", cta: "Proceed to booking details", title: "Booking details",
      lede: "When and where should the seller come to you?"
    },
    event_online: {
      step: "Attendee", cta: "Proceed to attendee details", title: "Attendee details",
      lede: "Who is attending? The ticket is issued in this name."
    },
    event_in_person: {
      step: "Attendee", cta: "Proceed to attendee details", title: "Attendee details",
      lede: "Who is attending? The ticket is issued in this name."
    }
  };
  var DETAIL_FALLBACK = {
    step: "Details", cta: "Proceed to details", title: "Your details",
    lede: "The seller needs these before this order can go ahead."
  };

  function detailCopy(form) {
    return DETAIL_COPY[form && form.details_kind] || DETAIL_FALLBACK;
  }

  // `active` is one-based and is never greater than 2 from this page, because 3
  // and 4 belong to Stripe and to the webhook.
  function stepsHtml(active, detailWord) {
    var names = [STEPS[0], detailWord || STEPS[1], STEPS[2], STEPS[3]];
    return "<ol class='steps' aria-label='Checkout progress'>" +
      names.map(function (name, index) {
        var position = index + 1;
        var tone = position < active ? "done" : (position === active ? "now" : "next");
        return "<li class='" + tone + "'" + (position === active ? " aria-current='step'" : "") + ">" +
          "<span class='dot' aria-hidden='true'>" +
            (position < active ? "&#10003;" : position) + "</span>" +
          "<span class='name'>" + esc(name) + "</span>" +
        "</li>";
      }).join("") + "</ol>";
  }

  function lineHtml(line) {
    var st = stateOf(line.state);
    var cover = line.cover_image_url
      ? "<img src='" + esc(line.cover_image_url) + "' alt='' loading='lazy'>"
      : "<img alt=''>";
    var moved = line.state === "price_changed";
    var price = moved ? line.price_now_minor : line.price_snapshot_minor;
    var was = moved
      ? "<p class='store'>Was " + esc(money(line.price_snapshot_minor, line.currency)) + "</p>"
      : "";
    // The quantity field and Remove are offered on every line, including the
    // ones that cannot be bought. A buyer looking at a sold-out line wants to
    // remove it, and a page that disables its controls when a line goes bad
    // leaves them with a cart they cannot clear.
    var confirm = moved
      ? "<button class='confirm' data-confirm-price='" + esc(line.line_id) + "'>Accept new price</button>"
      : "";
    // What the buyer chose. The API has returned this since before there was a
    // web cart and this file has never printed it, so two lines that differ
    // only by size rendered as the same row twice. `_variant_label` returns ""
    // when a variant names nothing it can stand behind -- its docstring says a
    // caller should then render nothing rather than an empty separator -- so
    // this is a presence test, not a truthiness convenience.
    var variant = line.variant_label
      ? "<p class='variant'>" + esc(line.variant_label) + "</p>"
      : "";
    var qty = line.qty || 1;
    // `<b>` below is the extended amount, which is the number this line adds to
    // the subtotal and therefore the one that has to be biggest. For a line of
    // three that leaves the unit price nowhere on the page, so it is printed
    // here -- and only when it differs from the extended amount, because
    // "$14.99 each" under "$14.99" is noise.
    var each = qty > 1
      ? "<span class='each'>" + esc(money(price, line.currency)) + " each</span>"
      : "";
    return "" +
      "<div class='line " + esc(st.tone) + "' data-line='" + esc(line.line_id) + "'>" +
        cover +
        "<div class='ident'>" +
          // `title` carries the whole name, because the heading is clamped to
          // two lines in CSS. The clamp is visual only -- the anchor's text is
          // still the full title for a screen reader -- and this gives a mouse
          // the same recovery.
          "<h3><a href='" + esc(productHref(line.listing_id)) + "' title='" + esc(line.title) + "'>" +
            esc(line.title) + "</a></h3>" +
          variant +
          was +
          "<span class='state'>" + esc(st.word) + "</span>" +
        "</div>" +
        "<div class='money'>" +
          "<b>" + esc(money(price * qty, line.currency)) + "</b>" +
          each +
          "<div class='controls'>" +
            confirm +
            "<input type='number' min='1' max='99' value='" + esc(line.qty) + "' " +
              "aria-label='Quantity' data-qty='" + esc(line.line_id) + "'>" +
            "<button data-remove='" + esc(line.line_id) + "'>Remove</button>" +
          "</div>" +
        "</div>" +
      "</div>";
  }

  // ----------------------------------------------------------------------
  // The buyer details form, rendered from the server's field list
  // ----------------------------------------------------------------------
  // Dispatch is on `field.type`, never on `field.key`, which is what keeps rule
  // 5 true: this function works for a field it has never seen, and breaks for
  // none of them. `country` is the one type that needs a list, and the list is
  // the server's too -- `checkout-options.shipping_countries`, the same source
  // Stripe's `allowed_countries` reads, so the picker cannot offer a country the
  // payment step refuses.
  var INPUT_TYPES = { phone: "tel", date: "date", time: "time" };

  function fieldHtml(sellerId, field, countries, typed) {
    var id = "cf-" + sellerId + "-" + String(field.key).replace(/[^a-z0-9_-]/gi, "");
    var value = typed[field.key] === undefined ? "" : typed[field.key];
    var attrs =
      " id='" + esc(id) + "' data-field='" + esc(field.key) + "'" +
      (field.autocomplete ? " autocomplete='" + esc(field.autocomplete) + "'" : "") +
      (field.required ? " required" : "");
    var control;
    if (field.type === "multiline") {
      control = "<textarea" + attrs + " rows='2'>" + esc(value) + "</textarea>";
    } else if (field.type === "country" || field.type === "choice") {
      var options = field.type === "country" ? countries : (field.options || []);
      control = "<select" + attrs + "><option value=''>Choose&hellip;</option>" +
        options.map(function (option) {
          return "<option value='" + esc(option) + "'" +
            (String(option) === String(value) ? " selected" : "") + ">" + esc(option) + "</option>";
        }).join("") + "</select>";
    } else {
      control = "<input type='" + esc(INPUT_TYPES[field.type] || "text") + "'" + attrs +
        " value='" + esc(value) + "'>";
    }
    return "<p class='field'><label for='" + esc(id) + "'>" + esc(field.label) +
      (field.required ? "" : " <span class='opt'>(optional)</span>") + "</label>" + control + "</p>";
  }

  function laneHtml(sellerId, question, chosen) {
    if (!question || !question.kind) return "";
    var id = "lane-" + sellerId;
    return "<p class='field'><label for='" + esc(id) + "'>How would you like this?</label>" +
      "<select id='" + esc(id) + "' data-lane='" + esc(sellerId) + "' required>" +
      "<option value=''>Choose&hellip;</option>" +
      (question.options || []).map(function (option) {
        return "<option value='" + esc(option.value) + "'" +
          (String(option.value) === String(chosen) ? " selected" : "") + ">" +
          esc(option.label) + "</option>";
      }).join("") + "</select></p>";
  }

  // The form for the lane the buyer chose, or `null` while an unanswered lane
  // question means the server has not yet said which questions apply. Guessing
  // one is how a buyer collecting in person ends up typing an address.
  function formFor(group) {
    var chosen = ui.lane[group.seller_user_id] || "";
    var forms = group.forms || {};
    if (group.lane_question && group.lane_question.kind) {
      return chosen && forms[chosen] ? forms[chosen] : null;
    }
    return forms[""] || null;
  }

  function checkoutFormHtml(group, options) {
    var sellerId = group.seller_user_id;
    var typed = ui.typed[sellerId] || {};
    var form = formFor(group);
    var countries = (options && options.shipping_countries) || [];
    var fields = (form && form.fields) || [];
    var pending = group.lane_question && group.lane_question.kind && !form;
    var copy = detailCopy(form);
    var held = heldError(sellerId);
    // §17/§20. The screenshot that opened this incident showed a refusal and an
    // active "Continue to secure payment" button on the same screen, under a
    // line reading "NEXT: SECURE PAYMENT" and above one promising to take the
    // buyer to Stripe to pay $6.25. Every one of those four was rendered
    // unconditionally; only `pending` -- an unanswered fulfilment question --
    // could ever disable the button. So a refusal the server knew was
    // unrecoverable was presented beside a working invitation to recover.
    //
    // `blocked` is the server's verdict, not this file's guess. A client that
    // infers retryability from copy is the defect, not the fix.
    var blocked = !!held && held.cta === "blocked";
    var offerPayment = !pending && !blocked;

    var body =
      laneHtml(sellerId, group.lane_question, ui.lane[sellerId]) +
      (pending
        ? "<p class='note'>Choose one to see what is needed.</p>"
        : fields.map(function (field) {
            return fieldHtml(sellerId, field, countries, typed);
          }).join(""));

    return "<form class='checkout' data-checkout='" + esc(sellerId) + "' novalidate>" +
      stepsHtml(2, copy.step) +
      "<h4>" + esc(copy.title) + "</h4>" +
      (pending ? "" : "<p class='step-lede'>" + esc(copy.lede) + "</p>") +
      body +
      // Re-emitted with whatever the last refusal said, because the redraw that
      // produces this element is the same redraw that would otherwise erase it.
      "<div data-group-error='" + esc(sellerId) + "'" + (held ? "" : " hidden") + ">" +
        (held ? groupErrorHtml(held.message) : "") + "</div>" +
      // Above the button, because it is what the button does and a buyer reading
      // downwards must meet it before the click rather than after it. Which is
      // also why it goes when the button goes: "Next: secure payment" above a
      // dead button is a worse sentence than no sentence.
      (offerPayment ? "<p class='next'>Next: secure payment</p>" : "") +
      "<div class='pay'>" +
        // Not "Pay". This button creates a Stripe Checkout Session and sends the
        // browser to Stripe's hosted page; no card is entered on this origin and
        // no charge is authorised by this click. Labelling a navigation as a
        // payment is how a buyer ends up believing they have paid while the
        // amount is still only reserved -- and how a real customer did.
        //
        // §22: the label survives a blocked refusal. The button is disabled,
        // not relabelled and not removed -- a control that vanishes leaves the
        // buyer unable to tell a broken order from a finished one, and the
        // refusal directly above it is already the explanation.
        "<button type='submit' class='button primary'" + (offerPayment ? "" : " disabled") + ">" +
          "Continue to secure payment &rarr;</button> " +
        "<button type='button' class='ghost' data-close-checkout='" + esc(sellerId) + "'>Back to cart</button>" +
      "</div>" +
      // The amount stays on the subtotal row above and on Stripe's page, which
      // are the two places it is authoritative. Repeating it inside the button
      // was what made the button read as a charge.
      //
      // Withheld for a blocked refusal for a narrower reason than the rest: it
      // is a statement of fact about what happens next ("You will continue to
      // Stripe's secure payment page to pay $6.25"), and next to a refusal that
      // cannot be retried it is simply untrue. The buyer in the incident read
      // this sentence nine times.
      (offerPayment
        ? "<p class='note'>You will continue to Stripe's secure payment page to pay " +
          esc(money(group.subtotal_minor, group.currency)) + ". Your card details are " +
          "never typed on PulseSoc and never reach our servers.</p>"
        : "") +
      "</form>";
  }

  // The app handoff, for a group the browser cannot finish. Injected by the
  // template from services/app_links.py rather than written here, so the app
  // registry stays the only thing that decides what a PulseSoc destination's
  // link looks like.
  function appCta(label) {
    var appHref = root.getAttribute("data-cart-app-href") || "";
    return appHref
      ? "<a class='button' href='" + esc(appHref) + "'>" + esc(label || "Open cart in the app") + "</a>"
      : "";
  }

  function groupFootHtml(group, options) {
    var sellerId = group.seller_user_id;

    // First, matching the order the checkout lane refuses in: `_require_user()`
    // is its opening statement. A guest is not short of a device, they are
    // short of an account, and the app would ask them for the same one -- so
    // this refusal gets a sign-in link and never the app handoff. `next`
    // returns them to this cart, which still holds their lines: the guest cart
    // is merged into the member's server-side at sign-in.
    if (group.sign_in_required) {
      return "<div class='group-foot'>" + subtotalRow(group) +
        "<p class='why'>" + esc(group.reason) + "</p>" +
        "<div class='pay'><a class='button primary' href='/login?next=" +
        encodeURIComponent(window.location.pathname) +
        "'>Sign in to check out</a></div></div>";
    }

    // The seller's own card verdict, not the platform's. `checkout-options`
    // answers per seller when asked with one, and the two disagree for every
    // seller who has not finished Connect onboarding -- exactly the case where a
    // pay button would be refused after the buyer committed to it.
    if (options && options.card_payments_available === false) {
      return "<div class='group-foot'>" + subtotalRow(group) +
        "<p class='why'>" + esc(options.payment_unavailable_message ||
          "Card payments are unavailable for this seller right now.") + "</p>" +
        "<div class='pay'>" + appCta() + "</div></div>";
    }

    if (!group.checkoutable) {
      return "<div class='group-foot'>" + subtotalRow(group) +
        "<p class='why'>" + esc(group.reason) + "</p>" +
        // Offered only where the app can actually do more than the page can. A
        // sold-out line is not fixed by switching device.
        (group.forms && Object.keys(group.forms).length
          ? ""
          : "<div class='pay'>" + appCta("Check out in the app") + "</div>") +
        "</div>";
    }

    if (ui.open === sellerId) {
      return "<div class='group-foot'>" + subtotalRow(group) +
        checkoutFormHtml(group, options) + "</div>";
    }

    // Closed, so the buyer is still on step one. The copy is the next step's
    // name rather than "Check out", which said nothing about whether the click
    // charged anything.
    var copy = detailCopy(formFor(group));
    return "<div class='group-foot'>" + subtotalRow(group) +
      stepsHtml(1, copy.step) +
      "<div class='pay'><button class='button primary' data-open-checkout='" + esc(sellerId) + "'>" +
      esc(copy.cta) + " &rarr;</button>" +
      "<p class='note'>No payment is taken yet &mdash; you will review and pay on " +
      "Stripe's secure page at the end.</p>" +
      "</div></div>";
  }

  function subtotalRow(group) {
    if (!group.subtotal_final) {
      // A total the buyer will not be charged is worse than no total: the lane
      // charges the stored snapshot, and an unconfirmed line's snapshot is the
      // old number.
      return "<div class='row grand'><span>Subtotal</span>" +
        "<span class='pending'>Not final yet</span></div>";
    }
    return "<div class='row grand'><span>Subtotal</span><b>" +
      esc(money(group.subtotal_minor, group.currency)) + "</b></div>";
  }

  function groupHtml(group, linesBySeller, options) {
    var lines = linesBySeller[group.seller_user_id] || [];
    return "<section class='group' data-group='" + esc(group.seller_user_id) + "'>" +
      "<header class='group-head'>" +
        "<h2>" + esc(group.seller_store_name) + "</h2>" +
        "<p>" + group.item_count + (group.item_count === 1 ? " item" : " items") + "</p>" +
      "</header>" +
      lines.map(lineHtml).join("") +
      groupFootHtml(group, options) +
      "</section>";
  }

  // The cart-wide footer. It counts and it hands off; it does not total. A sum
  // across sellers is not a number the buyer can pay in one action, and printing
  // one under a page of per-seller pay buttons is the same false promise this
  // rewrite exists to remove.
  function summaryHtml(groups) {
    var items = groups.reduce(function (sum, g) { return sum + g.item_count; }, 0);
    var payable = groups.filter(function (g) { return g.checkoutable; }).length;
    var rows =
      "<div class='row'><span>Items in your cart</span><span>" + items + "</span></div>" +
      (groups.length > 1
        ? "<div class='row'><span>Sellers</span><span>" + groups.length +
          " &mdash; each is paid separately</span></div>"
        : "") +
      (payable < groups.length
        ? "<div class='row'><span>Groups needing attention</span><span>" +
          (groups.length - payable) + "</span></div>"
        : "");
    return "<div class='totals'>" + rows +
      "<div class='pay'>" + appCta() +
        "<p class='note'>Your cart is the same cart the PulseSoc app shows &mdash; " +
        "open it and your items are waiting.</p>" +
      "</div></div>";
  }

  // The only writer of the cached payload, so `redraw()` below can never show a
  // group list the last fetch did not contain.
  function render(data, optionsBySeller) {
    ui.data = data;
    ui.optionsBySeller = optionsBySeller || {};
    ui.groups = (data && data.groups) || [];
    paint(data, ui.optionsBySeller);
  }

  // Re-render from what was last fetched, for the purely local changes -- open a
  // form, pick a lane. A refetch for those would cost a round trip and would
  // race a buyer who is still typing.
  function redraw() {
    if (ui.data) paint(ui.data, ui.optionsBySeller || {});
  }

  function paint(data, optionsBySeller) {
    var lines = (data && data.lines) || [];
    if (!lines.length) { show("empty"); return; }
    var groups = (data && data.groups) || [];

    var linesBySeller = {};
    lines.forEach(function (line) {
      var key = line.seller_user_id;
      (linesBySeller[key] = linesBySeller[key] || []).push(line);
    });

    // A group whose pay button is gone is a group whose open form is stale.
    if (ui.open && !groups.some(function (g) {
      return g.seller_user_id === ui.open && g.checkoutable;
    })) {
      ui.open = 0;
    }

    els.lines.innerHTML = groups.map(function (group) {
      return groupHtml(group, linesBySeller, optionsBySeller[group.seller_user_id]);
    }).join("");
    els.summary.innerHTML = summaryHtml(groups);
    show("lines");
  }

  function fail(message) {
    els.fail.innerHTML = "<div class='fail'><p>" + esc(message) +
      "</p><p><button data-cart-retry>Try again</button></p></div>";
    show("fail");
  }

  function load() {
    return pulseApi("/api/pulse/marketplace/cart")
      .then(function (data) {
        // checkout-options is asked per seller, because without a seller id it
        // answers only whether the card rail exists at all -- and that answer
        // disagrees with the per-seller one for every seller who has not
        // finished Connect onboarding. Its failure is survivable (the cart is
        // still worth showing) so each resolves to null rather than rejecting
        // the set; a group with no verdict renders its pay button and finds out
        // at the lane, which refuses before any money moves.
        var sellers = ((data && data.groups) || []).map(function (g) { return g.seller_user_id; });
        return Promise.all(sellers.map(function (sellerId) {
          return pulseApi("/api/pulse/marketplace/cart/checkout-options?seller_id=" +
                          encodeURIComponent(sellerId))
            .catch(function () { return null; });
        })).then(function (answers) {
          var bySeller = {};
          sellers.forEach(function (sellerId, index) { bySeller[sellerId] = answers[index]; });
          render(data, bySeller);
        });
      })
      .catch(function (err) {
        fail((err && err.message) || "Your cart could not be loaded.");
      });
  }

  // ----------------------------------------------------------------------
  // Checkout
  // ----------------------------------------------------------------------
  // FNV-1a, in the shift-add form that stays inside 32 bits -- the multiply form
  // loses precision above 2^53 and would collide in ways that are invisible
  // until two different carts share a key.
  function fingerprint(text) {
    var hash = 0x811c9dc5;
    for (var i = 0; i < text.length; i++) {
      hash ^= text.charCodeAt(i);
      hash = (hash + ((hash << 1) + (hash << 4) + (hash << 7) + (hash << 8) + (hash << 24))) >>> 0;
    }
    return ("0000000" + hash.toString(16)).slice(-8);
  }

  // The key is content-addressed, not random per page load. `POST /checkout`
  // replays the stored response for a repeated key, which is exactly right for a
  // double-tap and exactly wrong for a changed cart: a per-load key would hand
  // the buyer back the session it minted before they fixed their address or
  // their quantity, at the old amount. Hashing the request body makes an
  // identical request replay and any different one mint a new session. The count
  // and total ride in plaintext so a support question can be answered from the
  // key alone.
  function idempotencyKey(group, body) {
    return ("s" + group.seller_user_id + "-n" + group.item_count + "-t" + group.subtotal_minor +
            "-" + fingerprint(JSON.stringify(body))).slice(0, 120);
  }

  function groupErrorHtml(message) {
    return "<div class='fail'><p>" + esc(message) + "</p></div>";
  }

  // Remembered in `ui`, not only painted into the DOM.
  //
  // Both of the paths that refuse an attempt call `load()` on the line after
  // this one, to show the buyer the cart state that changed rather than only a
  // sentence about it -- and `load()` redraws the lines, which re-emits
  // `[data-group-error]` empty and hidden. So a message written straight to the
  // element was erased within the same tick it was written.
  //
  // Measured in a browser rather than reasoned about: after a refused session
  // the form came back with everything still typed in it, the button restored,
  // the cart intact -- and no sentence anywhere saying what had happened. That
  // is the shape of the incident this whole change exists to answer, where a
  // buyer tapped a button six times because nothing on screen told them why it
  // was not working.
  //
  // `ui.typed` is module-scoped for the same reason; this joins it.
  //
  // Stores a {message, cta} pair rather than a bare string, because the string
  // alone was not enough to render the form correctly and the previous code
  // proved it: with only a sentence to go on, `checkoutFormHtml` could do
  // nothing but keep offering payment. `cta` defaults to "retry" -- the prior
  // behaviour -- so the refusals raised locally in `checkout()` below, a lane
  // not chosen or a required field left empty, still invite the buyer onward.
  // Those really are retryable: the buyer fixes the field and continues.
  function groupError(sellerId, message, cta) {
    ui.error[sellerId] = message
      ? { message: message, cta: cta === "blocked" ? "blocked" : "retry" }
      : null;
    var slot = els.lines.querySelector("[data-group-error='" + sellerId + "']");
    if (!slot) { toast(message); return; }
    slot.innerHTML = groupErrorHtml(message);
    slot.hidden = false;
  }

  // One reader for the stored pair, so the shape lives in exactly two places.
  // Tolerates a bare string: `ui` survives across redraws and a message written
  // by an older bundle still in memory must not render as "[object Object]".
  function heldError(sellerId) {
    var held = ui.error[sellerId];
    if (!held) return null;
    if (typeof held === "string") return { message: held, cta: "retry" };
    return held.message ? held : null;
  }

  // The buyer has exactly one question when an attempt is refused -- did my
  // money move -- and the raw error is often incapable of answering it.
  // `pulseApi` surfaces its own read-deadline as "Request timed out", which is
  // accurate and tells a buyer nothing; the customer in the original incident
  // read silence as "it did not work, tap it again".
  //
  // The answer is the same for every refusal on this path, and it is safe to
  // state unconditionally: this request creates a Stripe Checkout session, and
  // a session is not a charge.
  //
  // This comment used to continue "...and the idempotency key means the retry
  // this invites resolves to that same session instead of minting a second
  // one." That was wrong, and it was wrong in the direction that caused the
  // incident. Stripe binds an idempotency key to the parameters of the first
  // request that used it, so a key replayed with changed parameters is not
  // handed back the original session -- it is refused with a 400, permanently,
  // for 24 hours. The retry this function invites was being *refused* rather
  // than deduplicated, nine times, and reported to the buyer as an outage.
  //
  // Post-fix the key co-varies with its parameters, so a retry does mint a
  // second session. What makes that safe is reachability, not reuse: the first
  // session's url is never written to the DB, never logged and never returned
  // in any response, and all three server failure paths expire it outright.
  //
  // Appended, never substituted: a server message that already explains itself
  // is the more useful half and is not thrown away for a generic one.
  //
  // `cta` decides whether a remedy is offered at all. Without it this function
  // appended "You can try again." to every refusal it did not recognise as
  // already carrying a remedy -- including, before the taxonomy change above,
  // the configuration failures where trying again could never work. That one
  // appended sentence is the exact text the buyer acted on for five hours.
  function handoffFailureMessage(err) {
    var blocked = err && err.cta === "blocked";
    var message = String((err && err.message) || "").trim();
    if (!message) return "We could not start checkout. Nothing has been charged.";
    if (!/[.!?]$/.test(message)) message += ".";
    if (!/charg/i.test(message)) message += " Nothing has been charged.";
    // The remedy clause is skipped whenever the message already carries one, in
    // any of the forms the route emits: "Try a different delivery address",
    // "Choose an option for every item", "Please try again". Matching only
    // "try again" appended a vaguer instruction to a specific one -- measured,
    // not supposed: four of the six refusal paths read "...Try a different
    // delivery address. ... You can try again."
    if (!blocked && !/\btry\b|retry|choose|pick|select|change/i.test(message)) {
      message += " You can try again.";
    }
    return message;
  }

  function findGroup(sellerId) {
    return (ui.groups || []).filter(function (g) {
      return String(g.seller_user_id) === String(sellerId);
    })[0];
  }

  function checkout(sellerId) {
    var group = findGroup(sellerId);
    if (!group || ui.busy) return;
    var form = formFor(group);
    if (!form) { groupError(sellerId, "Choose how you want this order fulfilled."); return; }

    var details = {};
    var missing = "";
    (form.fields || []).forEach(function (field) {
      var value = String((ui.typed[sellerId] || {})[field.key] || "").trim();
      if (value) details[field.key] = value;
      // Named by the server, so this check cannot demand a field the lane does
      // not, nor skip one it does.
      else if (field.required && !missing) missing = field.label;
    });
    if (missing) {
      groupError(sellerId, missing + " is required before you can continue to payment.");
      return;
    }

    var body = {
      seller_user_id: group.seller_user_id,
      fulfillment: ui.lane[sellerId] || "",
      fulfillment_details: details
    };
    body.idempotency_key = idempotencyKey(group, body);

    // `ui.busy` is the real double-submit guard -- `checkout()` returns early
    // above while it is set, and it is set before anything awaits, so a second
    // tap that lands between the click and the paint cannot reach the POST. The
    // `disabled` below is the visible half of the same statement, not the
    // enforcement; a disabled attribute alone is lost to the next re-render.
    // This attempt's own verdict replaces the last one; leaving a stale
    // refusal on screen while a new attempt is in flight states something
    // that is no longer being claimed.
    ui.error[sellerId] = null;
    ui.busy = true;
    var button = els.lines.querySelector("[data-checkout='" + sellerId + "'] button[type='submit']");
    var label = button ? button.innerHTML : "";
    // Says what is happening, which is a page being opened and not a card being
    // charged. The old "Starting checkout…" was vague in the one direction that
    // matters: a buyer reading it under a button that said "Pay" had every
    // reason to think the money was moving.
    if (button) { button.disabled = true; button.textContent = "Opening secure payment…"; }

    // Restores the form the buyer is looking at, with everything they typed
    // still in it -- `ui.typed` is module-scoped for exactly this, so a refused
    // attempt costs them a sentence to read and nothing to retype.
    function restore() {
      ui.busy = false;
      if (button) { button.disabled = false; button.innerHTML = label; }
    }

    pulseApi("/api/pulse/marketplace/cart/checkout", { method: "POST", body: JSON.stringify(body) })
      .then(function (answer) {
        if (answer && answer.checkout_url) {
          // Stripe's own page from here. The lines stay in the cart until the
          // webhook confirms payment, so an abandoned session leaves the buyer
          // exactly where they were. `ui.busy` is deliberately left set: the
          // navigation is already committed and clearing it would re-arm the
          // button for the moment before the browser leaves.
          window.location.href = answer.checkout_url;
          return;
        }
        // A success with nowhere to go is not a success the buyer can act on.
        restore();
        groupError(sellerId,
          "We could not open the secure payment page. No payment was attempted and " +
          "nothing has been charged. Your details are still here — try again.");
        load();
      })
      .catch(function (err) {
        restore();
        // Never "payment failed": no payment was attempted. The session could
        // not be created, which is a different sentence with a different remedy,
        // and the cart is not cleared either way.
        // The verdict rides from the server's classifier straight to the
        // button. `pulseApi` does `Object.assign(err, body)`, so `err.cta` is
        // whatever `classify_provider_exception` decided; an older server that
        // sends no verdict falls through to "retry", which is what this screen
        // already did.
        groupError(sellerId, handoffFailureMessage(err), err && err.cta);
        // The refusals are all about cart state -- a line went sold, a price
        // moved -- so the list is refetched to show the buyer the thing that
        // changed rather than only the sentence about it.
        load();
      });
  }

  // ----------------------------------------------------------------------
  // Events
  // ----------------------------------------------------------------------
  root.addEventListener("click", function (event) {
    var retry = event.target.closest("[data-cart-retry]");
    if (retry) { els.needsjs.hidden = false; load(); return; }

    var open = event.target.closest("[data-open-checkout]");
    if (open) {
      ui.open = parseInt(open.dataset.openCheckout, 10) || 0;
      redraw();
      var first = els.lines.querySelector("[data-checkout='" + ui.open + "'] [data-field],"
        + " [data-checkout='" + ui.open + "'] [data-lane]");
      if (first) first.focus();
      return;
    }

    var close = event.target.closest("[data-close-checkout]");
    if (close) { ui.open = 0; redraw(); return; }

    var remove = event.target.closest("[data-remove]");
    if (remove) {
      remove.disabled = true;
      pulseApi("/api/pulse/marketplace/cart/" + remove.dataset.remove, { method: "DELETE" })
        .then(load)
        .catch(function (err) { remove.disabled = false; toast(err.message); });
      return;
    }

    var accept = event.target.closest("[data-confirm-price]");
    if (accept) {
      accept.disabled = true;
      pulseApi("/api/pulse/marketplace/cart/" + accept.dataset.confirmPrice + "/confirm-price",
               { method: "POST", body: "{}" })
        .then(load)
        .catch(function (err) { accept.disabled = false; toast(err.message); });
    }
  });

  root.addEventListener("submit", function (event) {
    var form = event.target.closest("[data-checkout]");
    if (!form) return;
    event.preventDefault();
    checkout(form.dataset.checkout);
  });

  // `change` rather than `input` for quantity: typing "12" fires input twice and
  // would send a PATCH for the intermediate 1. Form fields are captured on
  // `input` instead, because they are not sent anywhere until Pay and losing the
  // last character typed before a click is its own bug.
  root.addEventListener("input", function (event) {
    var field = event.target.closest("[data-field]");
    if (!field) return;
    var form = field.closest("[data-checkout]");
    if (!form) return;
    var sellerId = form.dataset.checkout;
    (ui.typed[sellerId] = ui.typed[sellerId] || {})[field.dataset.field] = field.value;
  });

  root.addEventListener("change", function (event) {
    var lane = event.target.closest("[data-lane]");
    if (lane) {
      // The lane decides which questions apply, so answering it re-renders. What
      // was already typed is kept: the two lanes share their contact fields.
      ui.lane[lane.dataset.lane] = lane.value;
      redraw();
      return;
    }

    var field = event.target.closest("[data-field]");
    if (field && field.closest("[data-checkout]")) {
      var sellerId = field.closest("[data-checkout]").dataset.checkout;
      (ui.typed[sellerId] = ui.typed[sellerId] || {})[field.dataset.field] = field.value;
      return;
    }

    var qty = event.target.closest("[data-qty]");
    if (!qty) return;
    var quantity = Math.max(1, Math.min(99, parseInt(qty.value, 10) || 1));
    qty.value = quantity;
    pulseApi("/api/pulse/marketplace/cart/" + qty.dataset.qty,
             { method: "PATCH", body: JSON.stringify({ qty: quantity }) })
      .then(load)
      .catch(function (err) { toast(err.message); load(); });
  });

  load();
})();
