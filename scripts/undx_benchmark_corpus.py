"""Real phrasings for every UNDX capability, written to be *unlike* the registry.

The benchmark this feeds replaces one that proved nothing. ``pulsesoc_undx_phase2_
benchmark.py`` builds 2,336 cases by taking 73 sentences and putting 32 prefixes in
front of each, then checks that the tool name and permission it copied out of the
registry match the tool name and permission in the registry. Both halves are hollow:
the count is prefix padding over 73 distinct command bodies, and the assertion compares
the registry against itself.

So the rule for this file, and it is the whole point of it:

    **A paraphrase may not be an intent phrase.** Not verbatim, and not a bare intent
    with a courtesy word bolted on.

Every string below was written by asking "how would somebody actually ask for this",
not by reading ``spec.intents`` and reshuffling it. That is what makes the resulting
benchmark a test rather than a mirror — a matcher can only pass by *generalising* from
its intent phrases to language it has never been shown. Where a paraphrase does not
match, that is a coverage gap in the registry's intents, which is a finding and not a
bug in this file. Padding the intents until the benchmark goes green would reinstate
exactly the tautology this file exists to remove.

Three corpora live here:

``COMMANDS``
    capability id -> phrasings that must route to that capability.

``NEGATIVES``
    Messages that must route to *nothing*. Small talk, questions about UNDX itself, and
    requests for things PulseSoc does not do. A matcher that always finds something is
    a matcher that acts on small talk, and the failure is silent: the person gets an
    action they did not ask for and no error is raised anywhere.

``WRITE_GUARDS``
    Phrasings that mention a write in passing — asking *about* it, refusing it, asking
    what it would do — and must not reach the write capability. This is the class of
    mistake with real consequences, because a benchmark that only ever sends imperatives
    never discovers that "should I unfollow him?" is routed as "unfollow him".
"""

